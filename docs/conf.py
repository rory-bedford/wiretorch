def _add_icons(app, pagename, templatename, context, doctree):
    """The favicon sizes and the manifest, beyond Sphinx's single favicon."""
    root = context["pathto"]("_static/", 1)
    context["metatags"] = context.get("metatags", "") + _ICONS.format(root=root)


def setup(app):
    app.connect("html-page-context", _add_icons)
